export interface ParsedDobParts {
  day: string;   // 2-digit "01".."31"
  month: string; // 2-digit "01".."12"
  year: string;  // 4-digit "2015"
}

const MONTH_NAME_MAP: Record<string, string> = {
  jan: "01", january: "01",
  feb: "02", february: "02",
  mar: "03", march: "03",
  apr: "04", april: "04",
  may: "05",
  jun: "06", june: "06",
  jul: "07", july: "07",
  aug: "08", august: "08",
  sep: "09", sept: "09", september: "09",
  oct: "10", october: "10",
  nov: "11", november: "11",
  dec: "12", december: "12"
};

/**
 * Parses any DOB string (e.g. "2015-05-05", "05/05/2015", "05-05-2015", "5/5/2015",
 * "05-May-2015", "05052015", "20150505", "05/05/15") into normalized { day, month, year }.
 */
export function parseDobParts(rawDob?: string): ParsedDobParts | null {
  if (!rawDob) return null;
  const str = String(rawDob).trim();
  if (!str) return null;

  // 1. YYYY-MM-DD or YYYY/MM/DD (HTML <input type="date" /> format)
  const isoMatch = str.match(/^(\d{4})[-/.](\d{1,2})[-/.](\d{1,2})$/);
  if (isoMatch) {
    const year = isoMatch[1];
    const m = parseInt(isoMatch[2], 10);
    const d = parseInt(isoMatch[3], 10);
    if (m >= 1 && m <= 12 && d >= 1 && d <= 31) {
      return { day: String(d).padStart(2, "0"), month: String(m).padStart(2, "0"), year };
    }
  }

  // 2. DD-MM-YYYY or DD/MM/YYYY or D/M/YYYY (Indian / Samastha CSV standard)
  const dmyMatch = str.match(/^(\d{1,2})[-/.](\d{1,2})[-/.](\d{4})$/);
  if (dmyMatch) {
    const p1 = parseInt(dmyMatch[1], 10);
    const p2 = parseInt(dmyMatch[2], 10);
    const year = dmyMatch[3];
    if (p1 > 12 && p2 >= 1 && p2 <= 12) {
      return { day: String(p1).padStart(2, "0"), month: String(p2).padStart(2, "0"), year };
    }
    if (p2 > 12 && p1 >= 1 && p1 <= 12) {
      return { day: String(p2).padStart(2, "0"), month: String(p1).padStart(2, "0"), year };
    }
    if (p1 >= 1 && p1 <= 31 && p2 >= 1 && p2 <= 12) {
      return { day: String(p1).padStart(2, "0"), month: String(p2).padStart(2, "0"), year };
    }
  }

  // 3. DD-MMM-YYYY or DD MMM YYYY (e.g. "05-May-2015", "5 May 2015")
  const namedMonthMatch = str.match(/^(\d{1,2})[-/\s.,]+([a-zA-Z]+)[-/\s.,]+(\d{2,4})$/);
  if (namedMonthMatch) {
    const d = parseInt(namedMonthMatch[1], 10);
    const mStr = namedMonthMatch[2].toLowerCase();
    let yStr = namedMonthMatch[3];
    if (yStr.length === 2) {
      const yNum = parseInt(yStr, 10);
      yStr = yNum <= 40 ? `20${yStr}` : `19${yStr}`;
    }
    const month = MONTH_NAME_MAP[mStr] || MONTH_NAME_MAP[mStr.slice(0, 3)];
    if (month && d >= 1 && d <= 31) {
      return { day: String(d).padStart(2, "0"), month, year: yStr };
    }
  }

  // 4. DD-MM-YY or DD/MM/YY (2-digit year at end)
  const dmyShortMatch = str.match(/^(\d{1,2})[-/.](\d{1,2})[-/.](\d{2})$/);
  if (dmyShortMatch) {
    const p1 = parseInt(dmyShortMatch[1], 10);
    const p2 = parseInt(dmyShortMatch[2], 10);
    const yShort = parseInt(dmyShortMatch[3], 10);
    const year = yShort <= 40 ? `20${String(yShort).padStart(2, "0")}` : `19${String(yShort).padStart(2, "0")}`;
    if (p1 >= 1 && p1 <= 31 && p2 >= 1 && p2 <= 12) {
      return { day: String(p1).padStart(2, "0"), month: String(p2).padStart(2, "0"), year };
    }
  }

  // 5. Pure 8-digit string: either YYYYMMDD ("20150505") or DDMMYYYY ("05052015")
  const digits = str.replace(/\D/g, "");
  if (digits.length === 8) {
    const first4 = parseInt(digits.slice(0, 4), 10);
    const last4 = parseInt(digits.slice(4, 8), 10);
    if (first4 >= 1950 && first4 <= 2035) {
      const m = parseInt(digits.slice(4, 6), 10);
      const d = parseInt(digits.slice(6, 8), 10);
      if (m >= 1 && m <= 12 && d >= 1 && d <= 31) {
        return { day: String(d).padStart(2, "0"), month: String(m).padStart(2, "0"), year: String(first4) };
      }
    }
    if (last4 >= 1950 && last4 <= 2035) {
      const d = parseInt(digits.slice(0, 2), 10);
      const m = parseInt(digits.slice(2, 4), 10);
      if (m >= 1 && m <= 12 && d >= 1 && d <= 31) {
        return { day: String(d).padStart(2, "0"), month: String(m).padStart(2, "0"), year: String(last4) };
      }
    }
  }

  return null;
}

/**
 * Formats any DOB into DD/MM/YYYY for clear display (or returns trimmed original if unparseable)
 */
export function formatDobReadable(rawDob?: string): string {
  const parts = parseDobParts(rawDob);
  if (parts) return `${parts.day}/${parts.month}/${parts.year}`;
  return (rawDob || "").trim();
}

/**
 * Converts any DOB string into YYYY-MM-DD for HTML <input type="date" />
 */
export function toDobDateInputValue(rawDob?: string): string {
  const parts = parseDobParts(rawDob);
  if (parts) return `${parts.year}-${parts.month}-${parts.day}`;
  return "";
}

/**
 * Universal DOB matcher that compares student DOB and user-entered DOB across all date formats
 * (YYYY-MM-DD from calendar picker, DD/MM/YYYY, DD-MM-YYYY, DDMMYYYY, YYYYMMDD, or 4-digit birth year YYYY).
 */
export function doesDobMatch(studentDob?: string, enteredInput?: string): boolean {
  const sRaw = (studentDob || "").trim();
  const eRaw = (enteredInput || "").trim();
  if (!sRaw || !eRaw) return false;

  if (sRaw.toLowerCase() === eRaw.toLowerCase()) return true;

  const sParts = parseDobParts(sRaw);
  const eParts = parseDobParts(eRaw);

  if (sParts && eParts) {
    // Match exact year + month + day (or swapped day/month if CSV had MM/DD/YYYY)
    if (
      sParts.year === eParts.year &&
      ((sParts.month === eParts.month && sParts.day === eParts.day) ||
        (sParts.month === eParts.day && sParts.day === eParts.month))
    ) {
      return true;
    }
  }

  const sDigits = sRaw.replace(/\D/g, "");
  const eDigits = eRaw.replace(/\D/g, "");
  if (!sDigits || !eDigits) return false;

  if (sDigits === eDigits) return true;

  // Allow matching by 4-digit Birth Year (e.g. "2015")
  const sYear = sParts?.year || (sDigits.length >= 4 ? (sDigits.match(/(19\d{2}|20\d{2})/)?.[0] || "") : "");
  if (eDigits.length === 4 && sYear && eDigits === sYear) {
    return true;
  }
  if (sDigits.length === 4 && eParts?.year && sDigits === eParts.year) {
    return true;
  }

  return false;
}

